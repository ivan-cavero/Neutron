/// Vegetation classifier for BASE (no-veg) parity (moved from block_parity example).
pub fn is_vegetation_name(name: &str) -> bool {
    is_veg(name)
}

fn is_veg(name: &str) -> bool {
    let n = name.strip_prefix("minecraft:").unwrap_or(name);
    n.contains("leaves")
        || n.contains("log")
        || n.contains("wood")
        || n == "leaf_litter"
        || n == "vine"
        || n == "short_grass"
        || n == "tall_grass"
        || n == "grass"
        || n == "fern"
        || n == "large_fern"
        || n.contains("orchid")
        || n.contains("tulip")
        || n.contains("daisy")
        || n.contains("lilac")
        || n.contains("rose")
        || n.contains("peony")
        || n.contains("azalea")
        || n.contains("mushroom")
        || n == "dandelion"
        || n == "poppy"
        || n == "cornflower"
        || n == "oxeye_daisy"
        || n == "lily_of_the_valley"
        || n == "pink_petals"
        || n == "moss_carpet"
        || n == "moss_block"
        || n == "pale_moss_block"
        || n == "pale_moss_carpet"
        || n == "sculk"
        || n == "sculk_vein"
        || n == "sculk_sensor"
        || n == "sculk_catalyst"
        || n == "sculk_shrieker"
        || n == "glow_lichen"
        || n.contains("sapling")
        || n == "cave_vines"
        || n == "cave_vines_plant"
        || n == "hanging_roots"
        || n == "rooted_dirt"
        || n == "spore_blossom"
}
